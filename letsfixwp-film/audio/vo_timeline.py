"""Lay the voice-over lines on the film's clock and write src/vo.js (start/end of each line, subtitle text).
Each line starts at its cue (the beat sheet in TREATMENT.md) or 0.3 s after the previous line ends, whichever is later.
Run from anywhere: python3 audio/vo_timeline.py. Reads vo/lines.json and vo/dur.json."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
L = json.load(open(os.path.join(ROOT, 'vo/lines.json'))); D = json.load(open(os.path.join(ROOT, 'vo/dur.json')))
CUE = [.6, 3.0, 6.3, 12.9, 17.8, 21.3, 25.9, 29.4, 35.3, 38.4, 42.3]
DUR = 45.0
assert len(CUE) == len(L), 'one cue per line'
t = 0; out = []
for cue, l in zip(CUE, L):
    t0 = max(cue, t + .3); d = D[l['id']]
    out.append({'id': l['id'], 't0': round(t0, 3), 't1': round(t0 + d, 3), 'zh': l['text'], 'en': ''}); t = t0 + d
assert t < DUR - .8, f'voice runs to {t:.2f}, past the closing hold'
js = '// Voice-over lines on the film clock (generated by audio/vo_timeline.py from vo/). t0/t1 = speech start/end; zh holds the spoken line (English here).\n'
js += f'export const DUR = {DUR};\nexport const CREDIT_T = {DUR + 1};\nexport const VO = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n'
open(os.path.join(ROOT, 'src/vo.js'), 'w').write(js)
json.dump({'dur': DUR, 'lines': out}, open(os.path.join(ROOT, 'vo/timeline.json'), 'w'), ensure_ascii=False, indent=1)
print('dur', DUR)
for o in out: print(o['id'], o['t0'], o['t1'], o['zh'])
